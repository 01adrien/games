void setupContext(GameContext *ctx)
{
    // Setup map

    float miniMapWidth = MAP_WIDTH * TILE_SIZE * MAP_SCALE;
    float miniMapHeight = MAP_HEIGHT * TILE_SIZE * MAP_SCALE;

    int xMap = 0;
    int yMap = PLAYER_SCREEN_HEIGHT - miniMapHeight;
    ctx->mapPos = (Vector2){.x = xMap, .y = yMap};
    ctx->map = &level1[0][0];

    // Setup player
    int xPlayer = xMap + MAP_WIDTH * TILE_SIZE / 2; // (MAP_WIDTH * (TILE_SIZE * MAP_SCALE));
    int yPlayer = yMap + TILE_SIZE * 2;             // (MAP_HEIGHT * (TILE_SIZE * MAP_SCALE));
    ctx->player.dir = (Vector2){.x = 1, .y = 0};
    ctx->player.pos = (Vector2){.x = xPlayer, .y = yPlayer};
    ctx->player.vel = (Vector2){.x = 0, .y = 0};
    ctx->player.angle = PI;
    ctx->player.move.rot = ROT_NONE;
    ctx->player.move.dir = DIR_NONE;
    ctx->player.radius = PLAYER_RADIUS;
    ctx->player.plane = (Vector2){.x = 0, .y = 0.66};

    ctx->player.screen = (Rectangle){
        .x = (WIDTH - PLAYER_SCREEN_WIDTH) / 2,
        .y = (HEIGHT - PLAYER_SCREEN_HEIGHT) / 2,
        .width = PLAYER_SCREEN_WIDTH,
        .height = PLAYER_SCREEN_HEIGHT,
    };

    ctx->textures[TILE_GREYSTONE] = LoadTexture("../assets/textures/greystone.png");
    ctx->textures[TILE_BLUESTONE] = LoadTexture("../assets/textures/bluestone.png");
    ctx->textures[TILE_COLORSTONE] = LoadTexture("../assets/textures/colorstone.png");
    ctx->textures[TILE_WOOD] = LoadTexture("../assets/textures/wood.png");
    ctx->textures[TILE_REDBRICK] = LoadTexture("../assets/textures/redbrick.png");
    ctx->textures[TILE_EAGLE] = LoadTexture("../assets/textures/eagle.png");
}

int main(int argc, char const *argv[])
{
    InitWindow(WIDTH, HEIGHT, "Raycaster");
    SetTargetFPS(40);

    void *plugin_handle = NULL;
    DrawFuncPtr game = NULL;
    const char *file = "../build/raycaster_plugin.so";
    long lastPluginTime = 0;

    GameContext ctx;
    setupContext(&ctx);

    if (reload_plugin(file, &lastPluginTime, &game, &plugin_handle))
        return 1;

    while (!WindowShouldClose())
    {
        if (should_reload(file, &lastPluginTime))
            reload_plugin(file, &lastPluginTime, &game, &plugin_handle);

        BeginDrawing();
        ClearBackground(RAYWHITE);
        game(&ctx);
        DrawFPS(10, 10);
        EndDrawing();
    }

    for (size_t i = 1; i < TILE_COUNT; i++)
    {
        UnloadTexture(ctx.textures[i]);
    }

    return 0;
}
